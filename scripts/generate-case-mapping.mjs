import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

// Generate from the pinned UnicodeData.txt supplied as the first argument.
const source = await readFile(process.argv[2], 'utf8')
const expectedHash = '2fc713e6a31a87c4850a37fe2caffa4218180fadb5de86b43a143ddb4581fb86'
if (createHash('sha256').update(source).digest('hex') !== expectedHash) {
  throw new Error('Expected Unicode 15.1.0 UnicodeData.txt')
}
const upper = new Map()
const lower = new Map()
for (const line of source.trimEnd().split('\n')) {
  const fields = line.split(';')
  const code = parseInt(fields[0], 16)
  if (fields[12]) {
    upper.set(code, parseInt(fields[12], 16))
  }
  if (fields[13]) {
    lower.set(code, parseInt(fields[13], 16))
  }
}
const pairs = []
for (let code = 128; code <= 0x10ffff; code++) {
  const uppercase = upper.get(code) ?? code
  const normalized = lower.get(uppercase) ?? uppercase
  if (String.fromCodePoint(code).length !== String.fromCodePoint(normalized).length) {
    throw new Error(`Mapping changes UTF-16 width: ${code} -> ${normalized}`)
  }
  if (normalized !== code) {
    pairs.push(`[${code}, ${normalized}]`)
  }
}
const output = `// Generated by scripts/generate-case-mapping.mjs from Unicode 15.1.0 UnicodeData.txt.\n// Unicode data is distributed under the Unicode License v3: https://www.unicode.org/license.txt\n// Each entry is simple lowercase of simple uppercase, not Unicode full case folding.\nexport const unicodeCaseMapping = new Map<number, number>([\n  ${pairs.join(',\n  ')}\n])\n`
await writeFile('src/unicodeCaseMapping.ts', output)
